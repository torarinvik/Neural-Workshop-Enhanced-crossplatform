import assert from 'node:assert/strict';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { instantiateElisa } from '../shells/web/elisa-wasm-runtime.js';
import {decode, Kind} from '../shells/web/display-list.js';
const wasm = process.env.NWCORE_WASM_PATH ?? fileURLToPath(new URL('../build/nwcore.wasm', import.meta.url));
const {exports:e, instance} = await instantiateElisa(fs.readFileSync(wasm), {warn:false});
const task = BigInt(e.nw_api_v1_task_algebra());
const create = () => e.nw_api_v1_create(task,1n,3n,2n,0n,1n,0n,0n,19n);
let seq=0n;
const action=(r,ms,c,v=0)=>e.nw_api_v1_dispatch(r,1n,BigInt(ms),seq++,BigInt(c),BigInt(v),0n,0n,0n,0n,0n);
const info=(r,f)=>e.nw_api_v1_algebra_info(r,BigInt(f));
const oracle=create(), run=create();
const ptr=Number(e.nw_frame_alloc(1048576n));
for (const r of [oracle,run]) {
  assert.equal(action(r,100,0),1n);
  assert.equal(action(r,200,4),1n);
  const frameLength=Number(e.nw_api_v1_render(r,BigInt(ptr),1048576n,0n,912n,684n));
  const labels=decode(new Uint8Array(instance.exports.memory.buffer,ptr,frameLength).slice()).filter(c=>c.kind===Kind.TEXT).map(c=>c.text);
  assert.ok(labels.some(text=>text.startsWith('times before plus')));
  assert.equal(action(r,201,4),2n, 'clock sync only once');
  assert.equal(action(r,250,1,120),1n);
  assert.equal(action(r,1450,3),1n);
  assert.equal(info(r,14),0n, 'wrong answers do not establish a best level');
  assert.equal(info(r,15),1n);
  assert.equal(action(r,1600,0),1n);
  assert.equal(action(r,2000,4),1n);
}
assert.equal(action(oracle,2100,1,120),1n); assert.equal(action(oracle,4900,3),1n);
const answer=new TextDecoder().decode(Uint8Array.from({length:Number(info(oracle,10))},(_,i)=>Number(e.nw_api_v1_algebra_value(oracle,2n,BigInt(i)))));
for (const c of answer) assert.equal(action(run,2100,1,c.charCodeAt(0)),1n);
assert.equal(action(run,4900,3),1n);
assert.equal(info(run,8),1n); assert.equal(info(run,14),2n); assert.equal(info(run,15),2n); assert.equal(info(run,16),4n);
assert.equal(action(run,5000,0),1n); assert.equal(info(run,0),3n);
const n=Number(e.nw_api_v1_render(run,BigInt(ptr),1048576n,0n,912n,684n));
const texts=decode(new Uint8Array(instance.exports.memory.buffer,ptr,n).slice()).filter(c=>c.kind===Kind.TEXT).map(c=>c.text);
assert.ok(texts.includes('1 of 2 right, highest level 2'));
assert.equal(action(run,6000,0),1n); assert.equal(info(run,14),0n); assert.equal(info(run,15),0n); assert.equal(info(run,16),0n);
e.nw_api_v1_destroy(oracle); e.nw_api_v1_destroy(run);
console.log('Algebra score: timing, attempted count, correct best rung, summary and reset pass');
