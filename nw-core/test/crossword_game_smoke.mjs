assert.equal(exports.nw_api_v1_crossword_info(run, 0n), 0n);
assert.equal(exports.nw_api_v1_dispatch(run, 2n, 1000n, 0n, 1n, 0n, 0n, 0n, 0n, 0n, 0n), 1n);
assert.equal(exports.nw_api_v1_crossword_info(run, 0n), 1n);
assert.ok(exports.nw_api_v1_crossword_info(run, 4n) >= 0n);
const frame = Number(exports.nw_frame_alloc(1048576n));
assert.ok(exports.nw_api_v1_render(run, BigInt(frame), 1048576n, 0n, 912n, 684n) > 0n);
assert.equal(exports.nw_api_v1_dispatch(run, 8n, 1001n, 1n, 0n, 97n, 0n, 0n, 0n, 0n, 0n), 1n);
assert.equal(exports.nw_api_v1_dispatch(run, 2n, 1002n, 2n, 2n, 0n, 0n, 0n, 0n, 0n, 0n), 1n);
assert.equal(exports.nw_api_v1_crossword_info(run, 0n), 2n);
assert.equal(exports.nw_api_v1_destroy(run), 0n);
