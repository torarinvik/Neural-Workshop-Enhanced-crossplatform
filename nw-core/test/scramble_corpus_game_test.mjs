import assert from 'node:assert/strict';
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import {instantiateElisa} from '../shells/web/elisa-wasm-runtime.js';
import {decode, Kind} from '../shells/web/display-list.js';
const wasm = process.env.NWCORE_WASM_PATH ?? fileURLToPath(new URL('../build/nwcore.wasm', import.meta.url));
const {exports, instance} = await instantiateElisa(fs.readFileSync(wasm), {warn: false});
const task = BigInt(exports.nw_api_v1_task_scramble());
const run = exports.nw_api_v1_create(task, 1n, 1n, 1n, 1n, 0n, 0n, 0n, 17n);
const encoder = new TextEncoder();
const setCorpus = (index, sentences) => {
  const a = encoder.encode(index), b = encoder.encode(sentences);
  const p = a.length ? Number(exports.nw_frame_alloc(BigInt(a.length))) : 0;
  const q = b.length ? Number(exports.nw_frame_alloc(BigInt(b.length))) : 0;
  const memory = new Uint8Array(instance.exports.memory.buffer);
  memory.set(a, p); memory.set(b, q);
  const result = exports.nw_api_v1_scramble_set_corpus(run, BigInt(p), BigInt(a.length), BigInt(q), BigInt(b.length));
  if (q) exports.nw_frame_free(BigInt(q)); if (p) exports.nw_frame_free(BigInt(p));
  return result;
};
const info = field => Number(exports.nw_api_v1_scramble_info(run, BigInt(field)));
let seq = 0n;
const event = (kind, code, value=0n) => exports.nw_api_v1_dispatch(run, kind, 1000n + seq, seq++, code, value, 0n, 0n, 0n, 0n, 0n);
assert.equal(setCorpus('cat\t1\t\na\t2\t\n', 'a cat a cat a cat\n'), 0n);
assert.equal(info(13), 1);
assert.equal(setCorpus('invalid\n', 'a cat a cat a cat\n'), -3n);
assert.equal(info(13), 1, 'invalid replacement retains existing corpus');
assert.equal(event(1n, 0n), 1n);
assert.equal(info(0), 1);
assert.equal(setCorpus('cat\t1\t\na\t2\t\n', 'a cat a cat a cat\n'), -6n, 'active deal cannot be replaced');
for (const c of 'a cat a cat a cat') assert.equal(event(8n, 0n, BigInt(c.codePointAt(0))), 1n);
assert.equal(event(1n, 3n), 1n);
assert.equal(info(6), 1, 'source sentence is graded');
assert.equal(setCorpus('cat\t1\t\na\t2\t\n', 'unknown words are not in this corpus\n'), 0n);
assert.equal(event(1n, 0n), 1n);
assert.equal(info(0), 3, 'no eligible sentences ends without a fabricated deal');
for (let i = 0; i < 20; i++) {
  assert.equal(event(1n, 0n), 1n);
  assert.equal(info(0), 3, 'repeated empty-bank retries release temporary storage');
}
const pointer = Number(exports.nw_frame_alloc(1048576n));
const length = Number(exports.nw_api_v1_render(run, BigInt(pointer), 1048576n, 0n, 912n, 684n));
const labels = decode(new Uint8Array(instance.exports.memory.buffer, pointer, length).slice()).filter(c => c.kind === Kind.TEXT).map(c => c.text);
assert.ok(labels.some(text => text.includes('No sentence at this level')));
exports.nw_frame_free(BigInt(pointer));
assert.equal(setCorpus('cat\t1\t\na\t2\t\n', ''), 0n);
assert.deepEqual([info(14), info(15)], [1, 0]);
assert.equal(event(1n, 0n), 1n);
assert.equal(info(0), 3, 'seed sentences are filtered by the imported index');
assert.equal(setCorpus('', 'a cat a cat a cat\n'), 0n);
assert.deepEqual([info(14), info(15)], [0, 1]);
assert.equal(event(1n, 0n), 1n);
assert.equal(info(0), 1, 'imported sentences use the seed vocabulary');
for (const c of 'a cat a cat a cat') assert.equal(event(8n, 0n, BigInt(c.codePointAt(0))), 1n);
assert.equal(event(1n, 3n), 1n);
assert.equal(info(6), 1);
assert.equal(exports.nw_api_v1_destroy(run), 0n);
console.log('scramble_corpus_game_test: PASS (attach, invalid replacement, grading, empty bank, cleanup)');
