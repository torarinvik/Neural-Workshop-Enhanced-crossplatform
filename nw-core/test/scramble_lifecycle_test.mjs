import assert from 'node:assert/strict';
import fs from 'node:fs';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {instantiateElisa} from '../shells/web/elisa-wasm-runtime.js';

const wasm = process.env.NWCORE_WASM_PATH ?? fileURLToPath(new URL('../build/nwcore.wasm', import.meta.url));
const {exports} = await instantiateElisa(fs.readFileSync(wasm), {warn: false});
const source = JSON.parse(execFileSync('python3', [fileURLToPath(new URL('./scramble_seed_oracle.py', import.meta.url))], {encoding: 'utf8'}));
const task = BigInt(exports.nw_api_v1_task_scramble());
const run = exports.nw_api_v1_create(task, 1n, 1n, 2n, 1n, 1n, 0n, 0n, 17n);
let seq = 0n;
let clockOffset = 0n;
const event = (kind, code, value = 0n) => exports.nw_api_v1_dispatch(run, kind, 1000n + clockOffset + seq, seq++, code, value, 0n, 0n, 0n, 0n, 0n);
const info = field => Number(exports.nw_api_v1_scramble_info(run, BigInt(field)));
assert.equal(event(1n, 0n), 1n);
clockOffset += 10000n;
assert.equal(event(1n, 5n), 1n, 'the host starts the clock after generation');
assert.equal(event(1n, 5n), 2n, 'the clock can only be synchronized once');
assert.equal(event(1n, 3n), 2n, 'empty answer is refused');
assert.equal(info(0), 1);
for (const c of source[0].answer) assert.equal(event(8n, 0n, BigInt(c.codePointAt(0))), 1n);
clockOffset += 1200n;
assert.equal(event(1n, 3n), 1n);
assert.deepEqual([info(1), info(7), info(9), info(10)], [2, 1, 1, 1], 'correct answer climbs and records the solved rung');
assert.equal(info(16), 1, 'generation time is excluded');
assert.equal(event(1n, 0n), 1n);
clockOffset += 13000n;
assert.equal(event(1n, 5n), 1n);
assert.equal(event(8n, 0n, 120n), 1n);
clockOffset += 1700n;
assert.equal(event(1n, 3n), 1n);
assert.deepEqual([info(1), info(7), info(9), info(10)], [1, 1, 2, 1], 'wrong answer drops without raising best rung');
assert.equal(info(16), 2, 'elapsed time accumulates before truncation');
assert.equal(event(1n, 0n), 1n);
assert.equal(info(0), 3);
assert.equal(event(1n, 0n), 1n);
assert.deepEqual([info(0), info(1), info(2), info(7), info(9), info(10)], [1, 1, 1, 0, 0, 0], 'completed run restarts cleanly');
assert.equal(info(16), 0, 'restart clears elapsed time');
assert.equal(event(1n, 4n, 3n | (6n << 4n)), 1n);
assert.deepEqual([info(0), info(1), info(3), info(11), info(12)], [0, 3, 15, 0, 0]);
assert.equal(event(1n, 4n, 3n | (7n << 4n)), -6n, 'invalid option is rejected');
assert.equal(exports.nw_api_v1_destroy(run), 0n);
console.log('scramble_lifecycle_test: PASS (empty answer, adaptive results, restart, options)');
