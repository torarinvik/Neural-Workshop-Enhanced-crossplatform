#!/usr/bin/env python3
"""Differential harness for src/scene_counting.elisa against the REAL screen.

Four shape kinds and each is a different pyglet class -- Line, a closed Arc,
a closed MultiLine and a Box -- so the tangle is cycled through all four in
every trial big enough to hold them. This is the first scene to emit a
MultiLine, which is a header plus its points and comes back from the recorder
as one row.

The tangle is generated by the reference from its own RNG, so the shapes are
set here directly: what is under test is the drawing of a tangle, not the
dealing of one.

SPDX-License-Identifier: GPL-2.0-or-later
"""
import sys

import scenediff

scenediff.reexec()

from neural_workshop import display, geometry, state                # noqa: E402
from neural_workshop.ui.counting import (CIRCLES, Counting, LINES,   # noqa: E402
                                         RECTANGLES, TRIANGLES, Shape)

PHASES = {0: "ready", 1: "showing", 2: "hidden", 3: "feedback", 4: "done"}
KINDS = (LINES, CIRCLES, TRIANGLES, RECTANGLES)
TYPED = {0: '', 1: '7', 2: '41'}


def tangle(count):
    made = []
    for index in range(count):
        step = (index % 10) / 10.0
        points = ((0.05 + 0.6 * step, 0.08 + 0.5 * step),
                  (0.30 + 0.5 * step, 0.35 + 0.4 * step),
                  (0.55 + 0.3 * step, 0.62 + 0.2 * step))
        kind = KINDS[index % 4]
        # A line and a rectangle take two points; only a triangle takes three.
        keep = points if kind == TRIANGLES else points[:2]
        made.append(Shape(kind, keep, 0.06 + 0.012 * (index % 10)))
    return made


def build(spec):
    import framerec
    geometry.set_window_size(912, spec["tall"] // 2)
    display.relayout()
    if (geometry._width(), geometry._height()) != (1824, spec["tall"]):
        raise SystemExit("asked for 1824x%d pixels, got %dx%d"
                         % (spec["tall"], geometry._width(), geometry._height()))
    framerec.set_scale(geometry._width() / 912.0,
                       geometry._height() / (spec["tall"] / 2.0))
    state.cfg.BLACK_BACKGROUND = bool(spec["black"])
    screen = Counting()
    screen.shapes_data = tangle(spec["shapes"])
    screen.answer_text = TYPED[spec["typed"]]
    screen.trial = spec["trial"]
    screen.total_trials = spec["total_trials"]
    screen.correct = spec["right"]
    screen.phase = PHASES[spec["phase"]]
    screen.message = 'How many?'
    if spec["verdict"] >= 0:
        screen.verdict_shown = (bool(spec["verdict"]),
                                'Right' if spec["verdict"] else 'No')
    return screen, screen._build_chrome


if __name__ == "__main__":
    sys.exit(scenediff.main(build))
