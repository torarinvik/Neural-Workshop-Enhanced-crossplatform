#!/usr/bin/env python3
"""Generate Scramble's offline corpus from the original seed definitions."""
import ast
import json
from pathlib import Path
import sys

root = Path(__file__).resolve().parents[2]
original = root / 'original-neural-workshop-enhanced/neural_workshop'

def assignment(path, name):
    tree = ast.parse(path.read_text(encoding='utf-8'))
    node = next(n for n in tree.body if isinstance(n, ast.Assign) and
                any(isinstance(t, ast.Name) and t.id == name for t in n.targets))
    return node.value

words_node = assignment(original / 'wordlist.py', 'SEED_WORDS')
words = list(dict.fromkeys(ast.literal_eval(words_node.func.value).split()))
lines = ast.literal_eval(assignment(original / 'sentences.py', 'SEED_TEXT'))
for line in lines:
    for word in line.split():
        if word not in words:
            words.append(word)
vocab = ' '.join(words)
sentences = '\n'.join(lines) + '\n'
source = ('# Generated by scripts/generate_scramble_seed.py from the original offline corpus.\n'
          'module ScrambleSeed:\n'
          '    def vocabulary() -> sview:\n'
          f'        return sview({json.dumps(vocab)}, 0, -1)\n'
          '    def sentences() -> sview:\n'
          f'        return sview({json.dumps(sentences)}, 0, -1)\n')
target = root / 'nw-core/src/tasks/scramble_seed.elisa'
if '--check' in sys.argv:
    if target.read_text(encoding='utf-8') != source:
        raise SystemExit('Scramble seed corpus differs from original')
    print(f'scramble_seed_integrity: PASS ({len(words)} words, {len(lines)} sentences)')
else:
    target.write_text(source, encoding='utf-8')
