#!/usr/bin/env python3
"""Distil the word data syllogism needs into an Elisa source table.

The reference draws its names from a 12.7 MB frequency index fetched into the
user's Application Support directory. That index is data, not code: a browser
or a phone build cannot read it, and neither can a differential that wants to
be reproducible on a machine that never fetched it. So the two derived sets it
actually uses are distilled once, here, into a table the port compiles in.

`nouns` is the 3,450-word pool `_pool()` returns -- the names things get.

`taken` is the other half, and it is much smaller than it looks. `nonsense()`
checks each invented word against 142,000 real ones so that an invented name
never turns out to be a word -- but it can only ever invent words its syllable
machine can spell: onset + nucleus + coda, optionally twice, four to eight
letters. That is 2.55 million distinct strings, of which just 7,159 are real
English. A word outside that set can never be produced and so can never be
rejected, so the port carries those 7,159 and nothing else. The rejection
fires on about 12% of candidates, so it is not an edge case to skip.

    python3 scripts/words.py
"""
import os
import sys
import types

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(os.path.dirname(ROOT),
                                "original-neural-workshop-enhanced"))
sys.modules.setdefault("mujoco", types.ModuleType("mujoco"))

from neural_workshop import syllogism as sy


def emit_table(handle, name, words):
    handle.write("const %s_COUNT: i64 = %d\n\n" % (name.upper(), len(words)))
    handle.write("def %s_at(index: i64) -> cstr:\n" % name)
    handle.write("    can Abort.Panic:\n")
    # A flat if-chain would be 3,450 branches deep; a binary walk over the
    # sorted table keeps the generated function shallow and the lookup cheap.
    _emit_walk(handle, words, 0, len(words), 8)
    handle.write('        return ""\n')


def _emit_walk(handle, words, low, high, indent):
    pad = " " * indent
    if high - low <= 4:
        for at in range(low, high):
            handle.write('%sreturn "%s" if index == %d\n' % (pad, words[at], at))
        return
    mid = (low + high) // 2
    handle.write("%sif index < %d:\n" % (pad, mid))
    _emit_walk(handle, words, low, mid, indent + 4)
    handle.write("%selse:\n" % pad)
    _emit_walk(handle, words, mid, high, indent + 4)


def main():
    pool = sy._pool()
    if not pool:
        print("no word index on this machine; nothing to distil")
        return 1
    out = os.path.join(ROOT, "src", "tasks", "syllogism_words.elisa")
    with open(out, "w", encoding="utf-8") as handle:
        handle.write("# GENERATED by scripts/words.py -- do not edit.\n#\n")
        handle.write("# The noun pool syllogism names things after, distilled\n"
                     "# from the fetched frequency index so that the port\n"
                     "# needs no filesystem and no 12.7 MB of corpus.\n\n")
        emit_table(handle, "sy_noun", list(pool))
    print("wrote %s (%d nouns)" % (out, len(pool)))

    real = sy._real_words()
    syllables = [o + n + c for o in sy.ONSETS for n in sy.NUCLEI
                 for c in sy.CODAS]
    reachable = set()
    for one in syllables:
        if 4 <= len(one) <= 8:
            reachable.add(one)
        for two in syllables:
            word = one + two
            if 4 <= len(word) <= 8:
                reachable.add(word)
    taken = sorted(reachable & real)
    with open(out, "a", encoding="utf-8") as handle:
        handle.write("\n\n# The real English words `nonsense()` could invent"
                     " by accident, sorted.\n")
        handle.write("# See the module docstring: the syllable machine can"
                     " spell 2.55 million\n")
        handle.write("# distinct strings and only these are words, so"
                     " nothing else can ever be\n# rejected.\n\n")
        emit_table(handle, "sy_taken", taken)
    print("appended %d taken words (of %d real, %d reachable)"
          % (len(taken), len(real), len(reachable)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
