#!/usr/bin/env python3
"""Generate the web task menu registry from the reviewed catalog fixture."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "test/fixtures/task_catalog.json"
OUTPUT = ROOT / "shells/web/task-registry.js"


def quoted(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def render(manifest: dict) -> str:
    if manifest.get("schema_version") != 4:
        raise ValueError("task catalog schema_version must be 4")
    categories = manifest.get("categories")
    tasks = manifest.get("tasks")
    overrides = manifest.get("port_overrides")
    if not isinstance(categories, list) or not isinstance(tasks, list) or not isinstance(overrides, dict):
        raise ValueError("catalog requires categories, tasks, and port_overrides")

    category_ids = [row.get("id") for row in categories]
    if not category_ids or any(not isinstance(value, str) or not value for value in category_ids):
        raise ValueError("catalog categories must have non-empty IDs")
    if len(category_ids) != len(set(category_ids)):
        raise ValueError("catalog category IDs must be unique")

    task_ids = [row.get("id") for row in tasks]
    if any(not isinstance(value, str) or not value for value in task_ids):
        raise ValueError("catalog tasks must have non-empty IDs")
    if len(task_ids) != len(set(task_ids)):
        raise ValueError("catalog task IDs must be unique")
    unknown_overrides = set(overrides) - set(task_ids)
    if unknown_overrides:
        raise ValueError(f"port overrides reference unknown tasks: {sorted(unknown_overrides)}")

    grouped: list[list[dict]] = []
    for category_id in category_ids:
        rows = [row for row in tasks if row.get("category") == category_id]
        rows.sort(key=lambda row: row.get("position", -1))
        if [row.get("position") for row in rows] != list(range(len(rows))):
            raise ValueError(f"task positions in {category_id} must be contiguous from zero")
        grouped.append(rows)
    if any(row.get("category") not in category_ids for row in tasks):
        raise ValueError("a task references an unknown category")

    labels: list[list[str]] = []
    ids: list[list[str]] = []
    for rows in grouped:
        category_labels: list[str] = []
        category_ids_for_menu: list[str] = []
        for row in rows:
            override = overrides.get(row["id"], {})
            if not isinstance(override, dict):
                raise ValueError(f"port override for {row['id']} must be an object")
            label = override.get("label", row.get("label"))
            task_id = override.get("id", row["id"])
            if not isinstance(label, str) or not label or not isinstance(task_id, str) or not task_id:
                raise ValueError(f"invalid port override for {row['id']}")
            category_labels.append(label)
            category_ids_for_menu.append(task_id)
        labels.append(category_labels)
        ids.append(category_ids_for_menu)
    flat_ids = [task_id for row in ids for task_id in row]
    if len(flat_ids) != len(set(flat_ids)):
        raise ValueError("port task IDs must be unique after applying overrides")

    category_lines = []
    for category, category_labels in zip(categories, labels):
        task_values = ", ".join(quoted(label) for label in category_labels)
        category_lines.append(
            f"  Object.freeze({{ name: {quoted(category['label'])}, "
            f"tasks: Object.freeze([{task_values}]) }}),"
        )
    id_lines = [
        "  Object.freeze([" + ", ".join(quoted(task_id) for task_id in row) + "]),"
        for row in ids
    ]
    return (
        "// Generated by scripts/generate_task_registry.py from the reviewed task catalog.\n"
        "// Do not edit this file directly; update test/fixtures/task_catalog.json and regenerate.\n"
        "export const TASK_CATEGORIES = Object.freeze([\n"
        + "\n".join(category_lines)
        + "\n]);\n\n"
        "export const TASK_IDS_BY_CATEGORY = Object.freeze([\n"
        + "\n".join(id_lines)
        + "\n]);\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated output is stale")
    args = parser.parse_args()
    try:
        expected = render(json.loads(MANIFEST.read_text(encoding="utf-8")))
    except (OSError, json.JSONDecodeError, KeyError, TypeError, ValueError) as error:
        print(f"task registry generation failed: {error}", file=sys.stderr)
        return 1

    if args.check:
        try:
            actual = OUTPUT.read_text(encoding="utf-8")
        except OSError as error:
            print(f"task registry is missing: {error}", file=sys.stderr)
            return 1
        if actual != expected:
            print(f"task registry is stale: regenerate {OUTPUT}", file=sys.stderr)
            return 1
        print("PASS: web task registry matches reviewed catalog")
        return 0

    OUTPUT.write_text(expected, encoding="utf-8")
    print(f"generated {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
